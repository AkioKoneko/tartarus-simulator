'use strict';
const assert=require('node:assert/strict');
const {buildTargets}=require('../js/local-assist');
const st={phase:'manage',position:1,pending:[],cells:[{n:0},{n:1,sealed:false,inmate:{beast:'wolf'}},{n:2,sealed:false,inmate:{beast:'rat'}}]};
const rec={label:'Consume rat in cell 03',action:{type:'devour',to:2}};
const cells=[{n:1,kind:'inmate',beast:'wolf',x:200,y:300,k:1},{n:2,kind:'inmate',beast:'rat',x:400,y:300,k:1}];
const r={ok:true,cells,decision:{consume:true,targets:{consume:{x:300,y:600,width:140,height:24}}}};
const t=buildTargets(st,rec,{result:r});
assert.equal(t[0].kind,'button'); assert.equal(t[0].shape,'underline');
assert(t[0].y>r.decision.targets.consume.y+r.decision.targets.consume.height);
assert.equal(t[1].kind,'cell');assert.equal(t[1].x,400);
assert.deepEqual(buildTargets(st,rec,{result:{...r,decision:{consume:true}}}),[]);
assert.equal(buildTargets(st,rec,{result:{ok:true,cells,chain:{targets:[2]}}})[0].x,400);
assert.deepEqual(buildTargets(st,rec,{result:{ok:true,cells,chain:{targets:[1]}}}),[]);
assert.deepEqual(buildTargets(st,rec,{result:{ok:true,cells:cells.map(c=>({...c,x:NaN})),chain:{targets:[2]}}}),[]);
const gift={...st,pending:[{kind:'gift',options:['wine']}]};
const b={x:600,y:300,width:160,height:25};
const offered={ok:true,treasure:{ok:true,targets:{wine:b}}};
assert.equal(buildTargets(gift,{label:'Take Crimson Vintage',action:{type:'choose',id:'wine'}},{result:offered})[0].x,680);
assert.deepEqual(buildTargets(gift,{action:{type:'choose',id:'horn'}},{result:offered}),[]);
assert.deepEqual(buildTargets(st,rec,{result:{ok:false,cells}}),[]);
const tool={...st,pending:[{kind:'tool',options:['whip','shackles','fire'],rerolls:1}]};
const offer={ok:true,pick:{ok:true,cards:[{sim:'whip',conf:1,box:[100,200,220,360]},{sim:'shackles',conf:1,box:[400,200,520,360]}],reroll:true,rerollTarget:{x:200,y:600,width:130,height:25}}};
assert.equal(buildTargets(tool,{action:{type:'choose',id:'shackles'}},{result:offer})[0].x,460);
assert.equal(buildTargets(tool,{action:{type:'reroll'}},{result:offer})[0].shape,'underline');
assert.deepEqual(buildTargets(tool,{action:{type:'choose',id:'fire'}},{result:offer}),[]);
const duplicate={...offer,pick:{...offer.pick,cards:[offer.pick.cards[0],offer.pick.cards[0]]}};
assert.deepEqual(buildTargets(tool,{action:{type:'choose',id:'whip'}},{result:duplicate}),[]);
assert.deepEqual(buildTargets(tool,{action:{type:'reroll'}},{result:{...offer,pick:{...offer.pick,reroll:false}}}),[]);
const hunt={...st,tools:['trap'],used:{devour:0,swap:0},cells:[{n:0},{n:1,sealed:false,inmate:{beast:'lion'}},st.cells[2]]};
const huntCells=cells.map(c=>c.n===1?{...c,beast:'lion'}:c);
const huntRec={label:'Hunt rat in cell 03',action:{type:'hunt',to:2}};
const huntRead={ok:true,cells:huntCells,decision:{hunt:true,targets:{hunt:{x:700,y:600,width:80,height:24}}}};
const huntHints=buildTargets(hunt,huntRec,{result:huntRead});
assert.equal(huntHints[0].shape,'underline');assert.equal(huntHints[0].x,740);
assert.equal(huntHints[1].priority,'reference');assert.equal(huntHints[1].x,400);
const huntPicker={ok:true,cells:huntCells,decision:{ratway:true,framed:[2]}};
const huntPickState={...hunt,used:{...hunt.used,huntOnly:[2]}};
assert.equal(buildTargets(huntPickState,huntRec,{result:huntPicker})[0].x,400);
for(const state of [{...huntPickState,phase:'ratway'},{...huntPickState,tools:[]},{...huntPickState,used:{huntOnly:[1]}},{...huntPickState,used:{huntOnly:[2],hunt:1}}]) assert.deepEqual(buildTargets(state,huntRec,{result:huntPicker}),[]);
assert.deepEqual(buildTargets(huntPickState,huntRec,{result:{...huntPicker,decision:{ratway:true,framed:[1]}}}),[]);
assert.deepEqual(buildTargets(hunt,huntRec,{result:{...huntRead,decision:{hunt:true}}}),[]);
assert.deepEqual(buildTargets(hunt,huntRec,{result:{...huntRead,cells}}),[],'observed warden must still be a Lion');
console.log('PASS observed buttons, simultaneous victim, Hunt button/framed prey and Treasure gates');
