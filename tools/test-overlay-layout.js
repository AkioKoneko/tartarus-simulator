'use strict';
const assert = require('node:assert/strict');
const L = require('../desktop/lib/overlay-layout');
const area = { x: 0, y: 0, width: 2560, height: 1440 };
const settings = { collapsed: true, overlay: { x: 1100, y: 90 }, overlayWidth: 360 };
L.migrate(settings);
assert.deepEqual(settings.overlayIcon, { x: 1100, y: 90 });
L.remember(settings, { x: 1500, y: 120 }); settings.collapsed = false;
assert.deepEqual(L.bounds(settings, area, 230, () => true), { x: 1100, y: 90, width: 360, height: 230 });
L.remember(settings, { x: 30, y: 60 }); settings.collapsed = true;
assert.deepEqual(L.bounds(settings, area, 230, () => true), { x: 1500, y: 120, width: 56, height: 56 });
assert.deepEqual(settings.overlay, { x: 30, y: 60 });
settings.overlayIcon = null; L.migrate(settings);
assert.equal(settings.overlayIcon, null, 'Deliberate reset does not repeat migration');
assert.deepEqual(L.bounds(settings, { x: 2560, y: 0, width: 1920, height: 1080 }, 230, () => false), { x: 4400, y: 135, width: 56, height: 56 });
const expanded = { collapsed: false, overlay: { x: 100, y: 30 }, overlayWidth: 360 };
L.migrate(expanded);
assert.deepEqual(expanded.overlayIcon, { x: 404, y: 30 });
assert(L.visible({ x: 2516, y: -10, width: 56, height: 56 }, area));
assert(!L.visible({ x: 2555, y: 0, width: 56, height: 56 }, area));
assert(!L.visible({ x: 100, y: -100, width: 56, height: 56 }, area));
console.log('PASS independent positions, migration, reset and edge visibility');
